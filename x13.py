# Desenvolva um programa, utilizando while que mostre na tela de 0 até n
# em que n é o limite pelo usuário#

# numero limite
n=int(input('Informe um numero: '))
# contador
z=0
# executa o loop enquanto o contador for menor que limite
while z <= n:
    print(z)
    # incrementa ao contador para tornar o loop finito
    z += 1